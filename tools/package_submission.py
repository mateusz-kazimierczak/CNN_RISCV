#!/usr/bin/env python3
"""Package Git-visible sources and explicitly selected frozen evidence locally."""

from __future__ import annotations

import gzip
import hashlib
import io
import json
import subprocess
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def read(path):
    return json.loads(path.read_text())


def sha(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def files():
    # Git's exclusion rules keep machine credentials, .deps, raw job trees and
    # unrelated ignored files out of the source payload. Include new task files.
    inventory = subprocess.check_output(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z"],
        cwd=ROOT,
    )
    paths = {ROOT / p.decode() for p in inventory.split(b"\0") if p}
    software = read(ROOT / "results/profiling/B1-reordered/validation.json")
    hardware = read(ROOT / "results/profiling/hardware-progression/validation.json")
    identities = {v["capture_id"] for v in software["captures"] + hardware["captures"]}
    identities.add(software["accepted_reference_capture"])
    identities.add(hardware["software_bridge_capture"])
    for identity in identities:
        directory = ROOT / "build/profiling/compiler" / identity
        if not (directory / "manifest.json").exists():
            raise ValueError(f"selected capture is missing: {identity}")
        paths.update(p for p in directory.rglob("*") if p.is_file())
    paths.update(p for p in (ROOT / "build/profiling/B0").rglob("*") if p.is_file())
    for evidence in hardware["rtl"].values():
        snapshot = ROOT / evidence["source_snapshot"]
        if sha(snapshot) != evidence["snapshot_sha256"]:
            raise ValueError("archived RTL snapshot changed")
        paths.add(snapshot)
    for path in paths:
        if (
            not path.is_file()
            or path.is_symlink()
            or not path.resolve().is_relative_to(ROOT)
        ):
            raise ValueError(f"package requires ordinary repository files: {path}")
    return sorted(paths), identities


def main():
    paths, identities = files()
    records = {
        str(p.relative_to(ROOT)): {"sha256": sha(p), "bytes": p.stat().st_size}
        for p in paths
    }
    manifest = {
        "schema_version": 1,
        "source_policy": "Git-visible tracked and untracked files; ignored local settings excluded",
        "evidence_policy": "selected immutable software/hardware captures, frozen B0 raw profile and archived RTL snapshots",
        "capture_ids": sorted(identities),
        "files": records,
        "limits": "Dependencies/toolchains are not bundled. Native diagnostic build trees are regenerated by the software workflow. Physical area/Fmax and final report/slides remain separate deliverables.",
    }
    directory = ROOT / "build/submission"
    directory.mkdir(parents=True, exist_ok=True)
    destination = directory / "arch-project-submission.tar.gz"
    temporary = destination.with_suffix(".tmp")
    try:
        with (
            temporary.open("wb") as stream,
            gzip.GzipFile(
                filename="", mode="wb", fileobj=stream, mtime=0
            ) as compressed,
            tarfile.open(
                fileobj=compressed, mode="w|", format=tarfile.PAX_FORMAT
            ) as archive,
        ):
            for path in paths:
                relative = str(path.relative_to(ROOT))
                if sha(path) != records[relative]["sha256"]:
                    raise ValueError(f"package input changed: {relative}")
                info = archive.gettarinfo(str(path), arcname="arch_project/" + relative)
                info.uid = info.gid = info.mtime = 0
                info.uname = info.gname = ""
                with path.open("rb") as source:
                    archive.addfile(info, source)
            payload = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode()
            info = tarfile.TarInfo("arch_project/SUBMISSION-MANIFEST.json")
            info.size = len(payload)
            info.mode = 0o644
            archive.addfile(info, io.BytesIO(payload))
        # Verify the actual compressed payload, including every file's digest,
        # before publishing the archive path and checksum.
        observed = set()
        with tarfile.open(temporary, "r:gz") as archive:
            for member in archive:
                if not member.isfile() or not member.name.startswith("arch_project/"):
                    raise ValueError("unexpected archive entry")
                name = member.name.removeprefix("arch_project/")
                source = archive.extractfile(member)
                if name == "SUBMISSION-MANIFEST.json":
                    if json.load(source) != manifest:
                        raise ValueError("packaged manifest differs")
                else:
                    if name in observed or name not in records:
                        raise ValueError("duplicate or unexpected package file")
                    if (
                        hashlib.file_digest(source, "sha256").hexdigest()
                        != records[name]["sha256"]
                    ):
                        raise ValueError(f"packaged bytes differ: {name}")
                    observed.add(name)
        if observed != records.keys():
            raise ValueError("package file inventory incomplete")
        temporary.replace(destination)
    finally:
        temporary.unlink(missing_ok=True)
    (directory / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    )
    (directory / "SHA256SUMS").write_text(f"{sha(destination)}  {destination.name}\n")
    print(f"Submission archive: {destination}")
    print(
        f"{len(paths)} files; {len(identities)} frozen captures; {destination.stat().st_size:,} compressed bytes"
    )


if __name__ == "__main__":
    main()
